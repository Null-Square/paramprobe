"""G2b: fully learned nonlinear micro-MLPs under a fixed one-page probe budget.

This removes the closed-form linear-in-page-parameters structure of G2a. Each
semantic item is generated by its own two-layer tanh teacher. For a capacity
point with N pages, items sharing an address prefix must share one learned
student micro-MLP. The student operator shape, active FLOPs, q=1, and B=4096
stay fixed; only the number of available external pages changes.

Oracle routing is used intentionally in this gate so the experiment isolates
operator expressivity/optimization from routing reliability. G2a separately
measures learned-router degradation.
"""

from __future__ import annotations

import argparse
import math
import random

import numpy as np
import torch
from torch import nn


def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)


class PageMLPTable(nn.Module):
    """Training-time table; inference needs only the selected page's parameters."""

    def __init__(
        self,
        num_pages: int,
        input_dim: int,
        hidden_dim: int,
        output_dim: int,
    ) -> None:
        super().__init__()
        self.input_dim = input_dim
        self.hidden_dim = hidden_dim
        self.output_dim = output_dim
        self.w1 = nn.Embedding(num_pages, hidden_dim * input_dim)
        self.b1 = nn.Embedding(num_pages, hidden_dim)
        self.w2 = nn.Embedding(num_pages, output_dim * hidden_dim)
        self.b2 = nn.Embedding(num_pages, output_dim)
        nn.init.normal_(self.w1.weight, std=0.25 / math.sqrt(input_dim))
        nn.init.normal_(self.w2.weight, std=0.25 / math.sqrt(hidden_dim))
        nn.init.zeros_(self.b1.weight)
        nn.init.zeros_(self.b2.weight)

    @property
    def page_parameters(self) -> int:
        return (
            self.hidden_dim * self.input_dim
            + self.hidden_dim
            + self.output_dim * self.hidden_dim
            + self.output_dim
        )

    def forward(self, page_ids: torch.Tensor, x: torch.Tensor) -> torch.Tensor:
        batch = x.shape[0]
        w1 = self.w1(page_ids).view(batch, self.hidden_dim, self.input_dim)
        h = torch.tanh(
            torch.bmm(w1, x.unsqueeze(-1)).squeeze(-1) + self.b1(page_ids)
        )
        w2 = self.w2(page_ids).view(batch, self.output_dim, self.hidden_dim)
        return torch.bmm(w2, h.unsqueeze(-1)).squeeze(-1) + self.b2(page_ids)


def make_teacher(
    num_items: int,
    input_dim: int,
    hidden_dim: int,
    output_dim: int,
    rng: np.random.Generator,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor]:
    w1 = torch.from_numpy(
        rng.normal(
            scale=0.7 / math.sqrt(input_dim),
            size=(num_items, hidden_dim, input_dim),
        ).astype(np.float32)
    )
    b1 = torch.from_numpy(
        rng.normal(scale=0.2, size=(num_items, hidden_dim)).astype(np.float32)
    )
    w2 = torch.from_numpy(
        rng.normal(
            scale=0.8 / math.sqrt(hidden_dim),
            size=(num_items, output_dim, hidden_dim),
        ).astype(np.float32)
    )
    b2 = torch.from_numpy(
        rng.normal(scale=0.1, size=(num_items, output_dim)).astype(np.float32)
    )
    return w1, b1, w2, b2


def teacher_forward(
    params: tuple[torch.Tensor, torch.Tensor, torch.Tensor, torch.Tensor],
    item_ids: torch.Tensor,
    x: torch.Tensor,
) -> torch.Tensor:
    w1, b1, w2, b2 = params
    h = torch.tanh(
        torch.bmm(w1[item_ids], x.unsqueeze(-1)).squeeze(-1) + b1[item_ids]
    )
    return torch.bmm(w2[item_ids], h.unsqueeze(-1)).squeeze(-1) + b2[item_ids]


def page_ids_for_capacity(
    item_ids: np.ndarray, max_bits: int, used_bits: int
) -> np.ndarray:
    if used_bits == 0:
        return np.zeros_like(item_ids)
    return item_ids >> (max_bits - used_bits)


def run(args: argparse.Namespace) -> None:
    set_seed(args.seed)
    rng = np.random.default_rng(args.seed)

    if args.num_items != 2**args.max_bits:
        raise ValueError("G2b currently uses the complete 2^max_bits semantic space")

    page_parameters = (
        args.hidden_dim * args.input_dim
        + args.hidden_dim
        + args.output_dim * args.hidden_dim
        + args.output_dim
    )
    page_payload_bytes = page_parameters * 4
    if page_payload_bytes > args.block_bytes:
        raise ValueError("micro-MLP does not fit in one parameter page")

    teacher = make_teacher(
        args.num_items,
        args.input_dim,
        args.hidden_dim,
        args.output_dim,
        rng,
    )

    train_items_np = np.repeat(np.arange(args.num_items), args.train_queries_per_item)
    val_items_np = np.repeat(np.arange(args.num_items), args.val_queries_per_item)
    train_items = torch.from_numpy(train_items_np).long()
    val_items = torch.from_numpy(val_items_np).long()
    x_train = torch.from_numpy(
        rng.normal(size=(len(train_items_np), args.input_dim)).astype(np.float32)
    )
    x_val = torch.from_numpy(
        rng.normal(size=(len(val_items_np), args.input_dim)).astype(np.float32)
    )
    with torch.no_grad():
        y_train = teacher_forward(teacher, train_items, x_train)
        y_val = teacher_forward(teacher, val_items, x_val)
    target_energy = float(torch.mean(y_val**2))

    active_macs = (
        args.input_dim * args.hidden_dim
        + args.hidden_dim * args.output_dim
    )

    print("# ParamProbe G2b: fully learned page-sized micro-MLPs")
    print(f"seed={args.seed}")
    print(f"num_items={args.num_items}")
    print("router=oracle_prefix")
    print("q=1")
    print(f"block_bytes={args.block_bytes}")
    print(f"logical_bytes_per_query={args.block_bytes}")
    print(f"page_parameters={page_parameters}")
    print(f"page_payload_bytes={page_payload_bytes}")
    print(f"active_operator_macs_per_query={active_macs}")
    print()
    print("used_bits\tpages\texternal_MiB\tnormalized_mse")

    sweep = [0] + list(range(args.min_bits, args.max_bits + 1, args.bit_step))
    if sweep[-1] != args.max_bits:
        sweep.append(args.max_bits)

    for used_bits in sweep:
        num_pages = 1 if used_bits == 0 else 1 << used_bits
        semantic_ids = np.arange(args.num_items, dtype=np.int64)
        item_to_page = page_ids_for_capacity(
            semantic_ids, args.max_bits, used_bits
        )
        train_pages = torch.from_numpy(item_to_page[train_items_np]).long()
        val_pages = torch.from_numpy(item_to_page[val_items_np]).long()

        model = PageMLPTable(
            num_pages,
            args.input_dim,
            args.hidden_dim,
            args.output_dim,
        )
        optimizer = torch.optim.Adam(model.parameters(), lr=args.lr)

        for _ in range(args.epochs):
            order = torch.randperm(len(train_pages))
            for start in range(0, len(order), args.batch_size):
                idx = order[start : start + args.batch_size]
                prediction = model(train_pages[idx], x_train[idx])
                loss = torch.mean((prediction - y_train[idx]) ** 2)
                optimizer.zero_grad()
                loss.backward()
                optimizer.step()

        model.eval()
        with torch.no_grad():
            prediction = model(val_pages, x_val)
            normalized_mse = float(
                torch.mean((prediction - y_val) ** 2) / target_energy
            )

        external_mib = num_pages * args.block_bytes / (1024**2)
        print(
            f"{used_bits}\t{num_pages}\t{external_mib:.6f}\t"
            f"{normalized_mse:.8f}"
        )


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--num-items", type=int, default=256)
    parser.add_argument("--max-bits", type=int, default=8)
    parser.add_argument("--min-bits", type=int, default=2)
    parser.add_argument("--bit-step", type=int, default=2)
    parser.add_argument("--input-dim", type=int, default=8)
    parser.add_argument("--hidden-dim", type=int, default=32)
    parser.add_argument("--output-dim", type=int, default=8)
    parser.add_argument("--block-bytes", type=int, default=4096)
    parser.add_argument("--train-queries-per-item", type=int, default=96)
    parser.add_argument("--val-queries-per-item", type=int, default=24)
    parser.add_argument("--epochs", type=int, default=40)
    parser.add_argument("--batch-size", type=int, default=1536)
    parser.add_argument("--lr", type=float, default=1.5e-2)
    parser.add_argument("--seed", type=int, default=4)
    run(parser.parse_args())
